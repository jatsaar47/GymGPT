export function getMuscleName(muscle: MuscleGroup, lang: AppLanguage = "en"): string {
  if (!muscle) return "";
  const match = muscleTranslations[muscle];
  if (!match) return muscle;
  return lang === "hi" ? match.hi : match.en;
}

export function getMealName(mealType: MealType, lang: AppLanguage = "en"): string {
  const dict = translations[lang]?.meals || translations.en.meals;
  return dict[mealType] || mealType;
}

export function getFoodDisplayName(
  food: { name: string; hindiName?: string },
  lang: AppLanguage = "en"
): string {
  if (lang === "hi" && food.hindiName) {
    return food.hindiName;
  }
  return food.name;
}

export function getTranslations(lang?: string) {
  if (lang === "hi" || (typeof lang === "string" && lang.toLowerCase().startsWith("hi"))) {
    return translations.hi;
  }
  return translations.en;
}
